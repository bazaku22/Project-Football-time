const assert=require("node:assert/strict");
const {calculate}=require("../js/asian-handicap.js");
const balanced={home:1.2,away:1.2};
const dnb=calculate(balanced,0);
assert.ok(Math.abs(dnb.fullWin-dnb.fullLoss)<0.01);
assert.ok(dnb.push>20&&dnb.push<30);
assert.ok(Math.abs(dnb.fullWin+dnb.push+dnb.fullLoss-100)<1e-8);
const half=calculate(balanced,-0.5);
assert.ok(Math.abs(half.fullWin+half.fullLoss-100)<1e-8);
assert.equal(half.push,0);
const quarter=calculate(balanced,-0.25);
assert.ok(quarter.halfLoss>20);
assert.equal(quarter.halfWin,0);
assert.ok(Math.abs(quarter.fullWin+quarter.halfLoss+quarter.fullLoss-100)<1e-8);
const threeQuarter=calculate(balanced,-0.75);
assert.ok(threeQuarter.halfWin>0);
assert.equal(threeQuarter.halfLoss,0);
assert.ok(calculate({home:2,away:.8},-.5).fullWin>50);
assert.throws(()=>calculate({home:0,away:1},-.5));
console.log("Asian Handicap settlement tests passed.");
